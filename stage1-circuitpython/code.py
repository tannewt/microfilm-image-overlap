"""
Use the mouse to repeatedly scan microfilm controlled by Scan Pro.
Documented here: https://adafruit-playground.com/u/tannewt/pages/automated-microfilm-scanning

Requires (in /lib):
  - adafruit_hid/                 (keyboard, keyboard_layout_us, keycode)
  - absolute_mouse/               (Mouse + descriptor)

And a boot.py that enables the keyboard and the absolute mouse device,
e.g.:

    import usb_hid
    from absolute_mouse.descriptor import device
    usb_hid.enable((usb_hid.Device.KEYBOARD, device))

After writing boot.py you must reset the board so the USB devices
re-enumerate.

Before auto scanning, you must get the Scan Pro software setup. Load the
microfilm, find a page, adjust the rotation and zoom, do auto-brightness,
auto-contrast and auto-focus.

Select your desired DPI (save time will vary based on this!). Then save a test
file. The auto-saved files will be put in the same directory with the same
settings. The filename is autogenerated.
"""

# Test mode won't actually control the mouse or keyboard.
TEST = False
# Disable the display in case it is broken.
BROKEN_DISPLAY = False

# (x, y) Locations for different UI elements in Scan Pro. These are fractions of
# 16-bit values, NOT pixels. These locations work for the Seattle Public Library
# computers which have their monitors in portrait orientation.
SPEED_SLIDER = (12000, 27609)
PRINT_OR_SAVE = (9000, 28000)
HOME = (4000, 28000)
SAVE_BUTTON = (19000, 29000)
FOCUS_IN = (22000, 29200)

SLIDE_DIFF = 6200

# Time delays in the sequence. This fake mouse control doesn't actually know
# what the computer it is connected to is doing. Different computers or ScanPros
# may vary slightly.
MOVE_DELAY = 0.272
POST_MOVE_DELAY = 1
TAB_CLICK_DELAY = 0.05
FOCUS_DELAY = 0.8
SAVE_DIALOG_DELAY = 0.2
SAVE_DELAY = 1.2 # for full screen at 600dpi, LZW tiff

TOTAL_DELAY = MOVE_DELAY + POST_MOVE_DELAY + TAB_CLICK_DELAY * 2 + FOCUS_DELAY + SAVE_DIALOG_DELAY + SAVE_DELAY

import time
import displayio
import usb_hid
import random
import board
import gc
import keypad
import microcontroller
import struct
import supervisor

from absolute_mouse import Mouse
from adafruit_hid.keyboard import Keyboard
from adafruit_hid.keyboard_layout_us import KeyboardLayoutUS
from adafruit_hid.keycode import Keycode

import terminalio
from adafruit_display_text import label

import neopixel

mouse = Mouse(usb_hid.devices)
keyboard = Keyboard(usb_hid.devices)
layout = KeyboardLayoutUS(keyboard)

# Give the host a moment to enumerate the new HID devices.
time.sleep(1)

# Button Constants
BUTTON_LEFT = 7
BUTTON_UP = 6
BUTTON_DOWN = 5
BUTTON_RIGHT = 4
BUTTON_SELECT = 3
BUTTON_START = 2
BUTTON_A = 1
BUTTON_B = 0

def new_prefix():
    return f"{random.randint(0, 10000):05d}_{SLIDE_DIFF}_m{MOVE_DELAY:0.3f}_f{FOCUS_DELAY:0.1f}_d{SAVE_DIALOG_DELAY:0.1f}_s{SAVE_DELAY:0.1f}"

prefix = new_prefix()
print("Prefix:", prefix)

key_queue = keypad.ShiftRegisterKeys(
    clock=board.BUTTON_CLOCK,
    data=board.BUTTON_OUT,
    latch=board.BUTTON_LATCH,
    key_count=8,
    value_when_pressed=True,
)

display = board.DISPLAY
if not BROKEN_DISPLAY:
    display.auto_refresh = False
    print(display.width, display.height)

    text = "Hello world"
    group = displayio.Group()
    remaining_time_label = label.Label(terminalio.FONT, scale=2)
    remaining_time_label.x = 10
    remaining_time_label.y = 10
    group.append(remaining_time_label)
    remaining_scans_label = label.Label(terminalio.FONT)
    remaining_scans_label.x = 10
    remaining_scans_label.y = 30
    group.append(remaining_scans_label)
    total_scanned_label = label.Label(terminalio.FONT)
    total_scanned_label.x = 2
    total_scanned_label.y = display.height - 10
    group.append(total_scanned_label)
    state_label = label.Label(terminalio.FONT, text="")
    state_label.x = 10
    state_label.y = 100
    group.append(state_label)
    prefix_label = label.Label(terminalio.FONT, text=prefix)
    prefix_label.x = 40
    prefix_label.y = display.height - 10
    group.append(prefix_label)

    if TEST:
        test_label = label.Label(terminalio.FONT, text="TEST", scale=2, color=0xff0000, anchor_point=(0.5, 0.5))
        test_label.anchored_position = (display.width // 2, display.height // 2)
        group.append(test_label)

    board.DISPLAY.root_group = group
else:
    print("display off")
    display.brightness = 1

pixels = neopixel.NeoPixel(board.NEOPIXEL, 5, brightness=0.05, auto_write=False)

def fill_color(offset, count, color):
    if offset >= len(pixels):
        return offset
    for i in range(count // 2):
        if offset >= len(pixels):
            return offset
        pixels[offset] = color
        offset += 1
    if count % 2 == 1:
        if offset >= len(pixels):
            return offset
        pixels[offset] = tuple([comp // 2 for comp in color])
        offset += 1
    return offset

def scaled(start, now):
    _TICKS_PERIOD = (1<<29)
    _TICKS_MAX = (_TICKS_PERIOD-1)
    _TICKS_HALFPERIOD = (_TICKS_PERIOD//2)
    diff = (now - start) & _TICKS_MAX
    diff = ((diff + _TICKS_HALFPERIOD) & _TICKS_MAX) - _TICKS_HALFPERIOD
    if diff < 500:
        return 8
    return 64

SPEED_SLIDER = (12000, 27609)
PRINT_OR_SAVE = (9000, 28000)
HOME = (4000, 28000)
SAVE_BUTTON = (19000, 29000)
FOCUS_IN = (22000, 29200)
calibrate_index = 0
locations = [
    ["SPEED_SLIDER", "Speed Slider", SPEED_SLIDER],
    ["HOME", "Focus Tab", HOME],
    ["FOCUS_IN", "Focus +", FOCUS_IN],
    ["PRINT_OR_SAVE", "Save Tab", PRINT_OR_SAVE],
    ["SAVE_BUTTON", "Save button", SAVE_BUTTON]
]
save_format = "<BBBB" + "HH"*len(locations)
saved_size = struct.calcsize(save_format)
saved = struct.unpack(save_format, microcontroller.nvm[:saved_size])
if saved[0] == 0x25 and saved[1] == 1:
    for i, location in enumerate(locations):
        location[2] = (saved[4 + 2 * i], saved[4 + 2 * i + 1])
else:
    print("no saved values")

last_index = -1
last_x = 0
last_y = 0
pressed = {}
while calibrate_index < len(locations):
    if calibrate_index != last_index:
        current_x, current_y = locations[calibrate_index][2]
        remaining_time_label.text = locations[calibrate_index][1]
        remaining_scans_label.text = f"Click location {calibrate_index+1}/{len(locations)}"
        last_index = calibrate_index
        display.refresh()

    event = key_queue.events.get()
    if event:
        if event.released:
            if event.key_number in pressed:
                del pressed[event.key_number]
            if event.key_number == BUTTON_A:
                locations[calibrate_index][2] = (current_x, current_y)
                calibrate_index += 1
            elif event.key_number == BUTTON_B:
                calibrate_index -= 1
            calibrate_index = max(calibrate_index, 0)
        elif event.pressed:
            pressed[event.key_number] = event.timestamp
    now = supervisor.ticks_ms()
    if BUTTON_UP in pressed:
        current_y -= scaled(pressed[BUTTON_UP], now)
    if BUTTON_DOWN in pressed:
        current_y += scaled(pressed[BUTTON_DOWN], now)
    if BUTTON_LEFT in pressed:
        current_x -= scaled(pressed[BUTTON_LEFT], now)
    if BUTTON_RIGHT in pressed:
        current_x += scaled(pressed[BUTTON_RIGHT], now)

    if last_y != current_y or last_x != current_x:
        mouse.move(current_x, current_y)
        last_x = current_x
        last_y = current_y

new_saved = [0x25, 1, len(locations), 0]
for name, description, position in locations:
    globals()[name] = position
    new_saved.extend(position)

if new_saved != saved:
    microcontroller.nvm[:saved_size] = struct.pack(save_format, *new_saved)
    print("saved values")

if not TEST:
    mouse.move(*HOME)

def click(pos):
    if TEST:
        return
    mouse.move(*pos)
    mouse.press(Mouse.LEFT_BUTTON)
    mouse.release(Mouse.LEFT_BUTTON)

if not TEST:
    click(HOME)

remaining_scans = 0
scanning = False
i = 0
last_remaining_scans = 0

def process_buttons():
    global remaining_scans
    global scanning
    global i
    global prefix
    while True:
        event = key_queue.events.get()
        if not event:
            return
        if not event.released:
            continue

        if event.key_number == BUTTON_START:
            scanning = not scanning
            print("scanning", scanning)
        elif event.key_number == BUTTON_RIGHT:
            remaining_scans += 1
            print("remaining_scans + 1 =", remaining_scans)
        elif event.key_number == BUTTON_LEFT:
            remaining_scans = max(0, remaining_scans - 1)
            print("remaining_scans - 1 =", remaining_scans)
        elif event.key_number == BUTTON_UP:
            remaining_scans += 100
            print("remaining_scans + 100 =", remaining_scans)
        elif event.key_number == BUTTON_DOWN:
            remaining_scans = max(0, remaining_scans - 100)
            print("remaining_scans - 100 =", remaining_scans)
        elif event.key_number == BUTTON_SELECT:
            prefix = new_prefix()
            i = 0
            if not BROKEN_DISPLAY:
                prefix_label.text = prefix
            print("Prefix:", prefix)

while True:
    post_scan_delay = 0
    if remaining_scans > 0 and scanning:
        if not BROKEN_DISPLAY:
            state_label.text = f"Scanning"
            display.refresh()

        # 1. Move to the start position.
        # print("move to", SPEED_SLIDER)
        if not TEST:
            mouse.move(SPEED_SLIDER[0], SPEED_SLIDER[1])

        # 2. Press left mouse button.
        # print("press")
        if not TEST:
            mouse.press(Mouse.LEFT_BUTTON)

        # removed 0.4 delay we probably don't need

        if not TEST:
            mouse.move(SPEED_SLIDER[0] + SLIDE_DIFF, SPEED_SLIDER[1])
        # print("moved to", SPEED_SLIDER[0] + SLIDE_DIFF, SPEED_SLIDER[1])
        time.sleep(MOVE_DELAY)

        if not TEST:
            mouse.move(SPEED_SLIDER[0], SPEED_SLIDER[1])

        # 4. Release the left button.
        # print("release")
        if not TEST:
            mouse.release(Mouse.LEFT_BUTTON)
        time.sleep(POST_MOVE_DELAY)
        click(HOME)
        time.sleep(TAB_CLICK_DELAY)
        click(FOCUS_IN)
        time.sleep(FOCUS_DELAY)
        click(PRINT_OR_SAVE)
        time.sleep(TAB_CLICK_DELAY)
        click(SAVE_BUTTON)
        time.sleep(SAVE_DIALOG_DELAY)

        # 5. Type the filename using the US keyboard layout.
        filename = f"{prefix}_{i:04d}.tif"
        print("saving:", filename)
        if not TEST:
            layout.write(filename)

        # Optional: press Enter to confirm.
        if not TEST:
            keyboard.send(Keycode.ENTER)
        post_scan_delay = SAVE_DELAY
        remaining_scans -= 1
        i += 1

        print("remaining_scans =", remaining_scans)
    elif scanning:
        if not BROKEN_DISPLAY:
            state_label.text = "Done"
    else:
        if not BROKEN_DISPLAY:
            state_label.text = "Paused"

    start_time = time.monotonic()
    process_buttons()
    remaining_time = TOTAL_DELAY * remaining_scans
    if not BROKEN_DISPLAY:
        time_label = ""
        if remaining_time > 60 * 60:
            time_label += f"{int(remaining_time // (60 * 60)):d}h"
        if remaining_time > 60:
            time_label += f"{int((remaining_time // 60) % 60):02d}m"
        time_label += f"{remaining_time % 60:.1f}s"
        remaining_time_label.text = time_label
        remaining_scans_label.text = f"{remaining_scans}"
        total_scanned_label.text = f"{i}"
        display.refresh()
    gc.collect()

    if remaining_scans != last_remaining_scans:
        offset = fill_color(0, int(remaining_scans // 1000), (255, 255, 255))
        offset = fill_color(offset, int(remaining_scans % 1000 // 100), (255, 0, 0))
        offset = fill_color(offset, int(remaining_scans % 100 // 10), (0, 0, 255))
        offset = fill_color(offset, int(remaining_scans % 10), (0, 255, 0))
        for j in range(offset, len(pixels)):
            pixels[j] = (0, 0, 0)
        pixels.show()
        last_remaining_scans = remaining_scans

    remaining_sleep = post_scan_delay - (time.monotonic() - start_time)
    if remaining_sleep > 0:
        time.sleep(remaining_sleep)
